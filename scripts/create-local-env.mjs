// `pnpm setup:env` — writes a LOCAL-ONLY `.env` for the docker compose stack + `pnpm dev`.
// Every secret is freshly random; nothing here is ever used outside the Owner's computer (CLAUDE.md rule 8).
// Refuses to overwrite an existing .env.
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const target = resolve(import.meta.dirname, '..', '.env');
if (existsSync(target)) {
  console.error('.env already exists — not overwritten. Delete it first to regenerate.');
  process.exit(1);
}
const secret = (bytes = 32) => randomBytes(bytes).toString('hex');
const pg = { user: 'mytask', password: secret(16), db: 'mytask' };
const s3 = { key: `local${secret(6)}`, secret: secret(20) };
// Ed25519 key pair for access tokens (ADR-002 §1), stored as base64 of the PEM text (one line each).
const jwt = generateKeyPairSync('ed25519', {
  publicKeyEncoding: { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
});
const b64 = (pem) => Buffer.from(pem).toString('base64');

const lines = [
  '# LOCAL DEVELOPMENT ONLY — generated by `pnpm setup:env`. Never commit (git-ignored).',
  'NODE_ENV=development',
  'LOG_LEVEL=info',
  'APP_URL=http://localhost:3100',
  'ADMIN_URL=http://localhost:3200',
  'PORT=3000',
  'READINESS_PORT=3001',
  'WORKER_READINESS_PORT=3002',
  '',
  `POSTGRES_USER=${pg.user}`,
  `POSTGRES_PASSWORD=${pg.password}`,
  `POSTGRES_DB=${pg.db}`,
  `DATABASE_URL=postgresql://${pg.user}:${pg.password}@localhost:5432/${pg.db}`,
  'REDIS_URL=redis://localhost:6379',
  '',
  'S3_ENDPOINT=http://localhost:8333',
  'S3_REGION=us-east-1',
  `S3_ACCESS_KEY_ID=${s3.key}`,
  `S3_SECRET_ACCESS_KEY=${s3.secret}`,
  'S3_BUCKET_PUBLIC=public-media',
  'S3_BUCKET_PRIVATE=private',
  'S3_BUCKET_KYC=kyc',
  'PUBLIC_MEDIA_BASE_URL=http://localhost:8333/public-media',
  '',
  '# Empty with `pnpm dev` (no Caddy). The apps profile sets 172.30.0.10 for the api container.',
  'TRUSTED_PROXY_IPS=',
  `INTERNAL_SERVICE_TOKEN=${secret(32)}`,
  `JWT_PRIVATE_KEY=${b64(jwt.privateKey)}`,
  `JWT_PUBLIC_KEY=${b64(jwt.publicKey)}`,
  `SETTINGS_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
  '',
  'API_INTERNAL_URL=http://localhost:3000/api/v1',
  'API_DEV_PROXY_ORIGIN=http://localhost:3000',
  '# Set to http://<this computer LAN IP>:3000/api/v1 to use the app on a phone (docs/SETUP-LOCAL.md)',
  'EXPO_PUBLIC_API_URL=http://localhost:3000/api/v1',
  '',
  'SMTP_URL=smtp://localhost:1025',
  'MAIL_FROM_ADDRESS=no-reply@mytask.local',
  'MAIL_FROM_NAME=MyTask.ge (local)',
  'BOG_API_BASE_URL=http://localhost:4100',
  'CLAMAV_HOST=localhost',
  '',
];
writeFileSync(target, lines.join('\n'), { mode: 0o600 });
console.log(`Wrote ${target} with fresh local-only secrets.`);
